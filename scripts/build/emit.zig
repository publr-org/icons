//! The three adapters: TypeScript for browsers and the editor, Zig for the CMS
//! and design system, and the manifest every other tool reads. Output is
//! byte-identical to the node scripts these replaced, so consumers see no diff.
const std = @import("std");
const svg = @import("svg.zig");
const json = @import("json.zig");

pub const header = "// Generated by scripts/build.zig; do not edit.\n";
pub const view_box = "0 0 24 24";

const typescript_tail = @embedFile("typescript_tail.ts");
const zig_tail = @embedFile("zig_tail.zig");

pub fn typescript(allocator: std.mem.Allocator, icons: []const svg.Icon) ![]const u8 {
    std.debug.assert(icons.len > 0);

    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const writer = &out.writer;

    try writer.writeAll(header);
    try writer.writeAll("\nexport const ICON_VIEWBOX = \"" ++ view_box ++ "\" as const;\nexport type IconName = ");

    for (icons, 0..) |icon, index| {
        if (index > 0) {
            try writer.writeAll(" | ");
        }

        try json.write_string(writer, icon.name);
    }

    try writer.writeAll(";\n\nexport const ICONS: Readonly<Record<IconName, string>> = {\n");

    for (icons) |icon| {
        try writer.writeAll("  ");
        try json.write_string(writer, icon.name);
        try writer.writeAll(": ");
        try json.write_string(writer, icon.body);
        try writer.writeAll(",\n");
    }

    try writer.writeAll("};\n\n");
    try writer.writeAll(typescript_tail);

    std.debug.assert(out.written().len > header.len);

    return out.toOwnedSlice();
}

pub fn zig_adapter(allocator: std.mem.Allocator, icons: []const svg.Icon) ![]const u8 {
    std.debug.assert(icons.len > 0);

    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const writer = &out.writer;

    try writer.writeAll(header);
    try writer.writeAll("\npub const view_box = \"" ++ view_box ++ "\";\npub const Name = enum { ");

    for (icons, 0..) |icon, index| {
        if (index > 0) {
            try writer.writeAll(", ");
        }

        try write_identifier(writer, icon.name);
    }

    try writer.writeAll(" };\n\n");

    for (icons, 0..) |icon, index| {
        if (index > 0) {
            try writer.writeAll("\n\n");
        }

        try writer.writeAll("pub const ");
        try write_identifier(writer, icon.name);
        try writer.writeAll(": []const u8 =\n");
        try write_multiline(writer, icon.body);
        try writer.writeAll("\n;");
    }

    try writer.writeAll("\n\n");
    try writer.writeAll(zig_tail);

    std.debug.assert(out.written().len > header.len);

    return out.toOwnedSlice();
}

pub fn manifest(allocator: std.mem.Allocator, icons: []const svg.Icon) ![]const u8 {
    std.debug.assert(icons.len > 0);

    var out: std.Io.Writer.Allocating = .init(allocator);
    errdefer out.deinit();
    const writer = &out.writer;

    try writer.writeAll("{\n  \"schemaVersion\": 1,\n  \"viewBox\": \"" ++ view_box ++ "\",\n  \"icons\": [\n");

    for (icons, 0..) |icon, index| {
        if (index > 0) {
            try writer.writeAll(",\n");
        }

        try writer.writeAll("    {\n      \"name\": ");
        try json.write_string(writer, icon.name);
        try writer.writeAll(",\n      \"file\": ");
        try json.write_string(writer, icon.file);
        try writer.writeAll("\n    }");
    }

    try writer.writeAll("\n  ]\n}\n");

    std.debug.assert(out.written().len > 0);

    return out.toOwnedSlice();
}

/// `kebab-case` as a Zig identifier: `kebab_case`.
fn write_identifier(writer: *std.Io.Writer, name: []const u8) !void {
    for (name) |byte| {
        try writer.writeByte(if (byte == '-') '_' else byte);
    }
}

/// Each non-blank line of the body, trimmed, as one `\\` multiline-literal line.
fn write_multiline(writer: *std.Io.Writer, body: []const u8) !void {
    var lines = std.mem.splitScalar(u8, body, '\n');
    var first = true;

    while (lines.next()) |raw| {
        const line = std.mem.trim(u8, raw, " \t\r\x0b\x0c");

        if (line.len == 0) {
            continue;
        }

        if (!first) {
            try writer.writeByte('\n');
        }

        first = false;
        try writer.writeAll("    \\\\");
        try writer.writeAll(line);
    }

    std.debug.assert(!first);
}

test "manifest lists every icon in order" {
    const icons = [_]svg.Icon{
        .{ .name = "a-b", .file = "a-b.svg", .source = "", .body = "<g/>" },
        .{ .name = "c", .file = "c.svg", .source = "", .body = "<g/>" },
    };
    const out = try manifest(std.testing.allocator, &icons);
    defer std.testing.allocator.free(out);
    try std.testing.expectEqualStrings(
        "{\n  \"schemaVersion\": 1,\n  \"viewBox\": \"0 0 24 24\",\n  \"icons\": [\n" ++
            "    {\n      \"name\": \"a-b\",\n      \"file\": \"a-b.svg\"\n    },\n" ++
            "    {\n      \"name\": \"c\",\n      \"file\": \"c.svg\"\n    }\n  ]\n}\n",
        out,
    );
}

test "the zig adapter turns dashes into underscores and lines into a multiline literal" {
    const icons = [_]svg.Icon{
        .{ .name = "a-b", .file = "a-b.svg", .source = "", .body = "<g>\n  <path/>\n</g>" },
    };
    const out = try zig_adapter(std.testing.allocator, &icons);
    defer std.testing.allocator.free(out);
    try std.testing.expect(std.mem.indexOf(u8, out, "pub const Name = enum { a_b };") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "pub const a_b: []const u8 =\n    \\\\<g>\n    \\\\<path/>\n    \\\\</g>\n;") != null);
}
